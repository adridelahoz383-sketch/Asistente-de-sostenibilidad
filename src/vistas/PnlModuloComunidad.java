    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String id = txtIdComunidad.getText().trim();
        String nombre = txtNombre.getText().trim();
        String ubicacion = txtUbicacion.getText().trim();

        if (boxEstrato.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione un estrato socioeconómico válido.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int estrato = Integer.parseInt(boxEstrato.getSelectedItem().toString());

        if (id.isEmpty() || nombre.isEmpty() || ubicacion.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        id = id.replace(";", "");
        nombre = nombre.replace(";", "");
        ubicacion = ubicacion.replace(";", "");

        Comunidad copropiedadActualizada = new Comunidad(nombre, id, ubicacion, estrato);

        List<Comunidad> listaComunidades = new ArrayList<>();

        listaComunidades.add(copropiedadActualizada);

        ControladorPersistencia persistencia = new ControladorPersistencia();
        persistencia.guardarComunidades(listaComunidades);

        JOptionPane.showMessageDialog(this, "Información de la copropiedad actualizada con éxito.", "Éxito", JOptionPane.INFORMATION_MESSAGE);

        txtIdComunidad.setEditable(false);
        comunidadExiste = true;
    }//GEN-LAST:event_btnGuardarActionPerformed


