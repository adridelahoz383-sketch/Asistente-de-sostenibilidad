    private void cargarDatosCopropiedad() {
        ControladorPersistencia persistencia = new ControladorPersistencia();
        List<Comunidad> lista = persistencia.cargarComunidades();

        if (!lista.isEmpty()) {
            Comunidad miComunidad = lista.get(0);

            txtIdComunidad.setText(miComunidad.getIdComunidad());
            txtNombre.setText(miComunidad.getNombre());
            txtUbicacion.setText(miComunidad.getUbicacion());

            boxEstrato.setSelectedItem(String.valueOf(miComunidad.getEstrato()));

            txtIdComunidad.setEditable(false);
        } else {
            txtIdComunidad.setText("1001");
            txtIdComunidad.setEditable(true);
        }
    }

