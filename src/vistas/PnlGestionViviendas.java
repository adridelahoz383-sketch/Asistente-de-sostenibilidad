    private void cargarViviendasEnTabla() {

        modeloTabla.setRowCount(0);

        ControladorPersistencia dePersistencia = new ControladorPersistencia();

        List<Comunidad> comunidades = dePersistencia.cargarComunidades();

        if (!comunidades.isEmpty()) {

            List<Vivienda> listaViviendas = dePersistencia.cargarViviendas(comunidades);

            for (Vivienda viv : listaViviendas) {
                Object[] fila = {
                    viv.getIdVivienda(),
                    viv.getAreaVivienda(),
                    viv.getNombrePropietario(),
                    viv.getCedulaPropietario(),
                    viv.getDireccion()
                };
                modeloTabla.addRow(fila);
            }
        }
    }

