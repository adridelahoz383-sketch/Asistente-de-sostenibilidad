    private void btnGuardarViviendaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarViviendaActionPerformed

        String idViv = txtIdVivienda.getText().trim();
        String areaStr = txtArea.getText().trim();
        String nombre = txtPropietario.getText().trim();
        String cedula = txtCedula.getText().trim();
        String direccion = txtDireccion.getText().trim();

        if (idViv.isEmpty() || areaStr.isEmpty() || nombre.isEmpty() || cedula.isEmpty() || direccion.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Diligencie todos los campos de la vivienda.", "Campos Incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double area = Double.parseDouble(areaStr);

            idViv = idViv.replace(";", "");
            nombre = nombre.replace(";", "");
            cedula = cedula.replace(";", "");
            direccion = direccion.replace(";", "");

            ControladorPersistencia dePersistencia = new ControladorPersistencia();
            List<Comunidad> comunidades = dePersistencia.cargarComunidades();

            if (comunidades.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Error: Debe configurar primero los datos de 'Mi Copropiedad' antes de añadir viviendas.", "Falta Comunidad Maestra", JOptionPane.ERROR_MESSAGE);
                return;
            }

            Comunidad comunidadActual = comunidades.get(0);
            List<Vivienda> listaTotalViviendas = dePersistencia.cargarViviendas(comunidades);

            for (Vivienda v : listaTotalViviendas) {
                if (v.getIdVivienda().equalsIgnoreCase(idViv)) {
                    JOptionPane.showMessageDialog(this, "El ID de vivienda '" + idViv + "' ya se encuentra registrado.", "Inmueble Duplicado", JOptionPane.ERROR_MESSAGE);
                    return;
                }
            }

            Vivienda nuevaVivienda = new Vivienda(comunidadActual, idViv, area, nombre, cedula, direccion);
            listaTotalViviendas.add(nuevaVivienda);

            dePersistencia.guardarViviendas(listaTotalViviendas);
            JOptionPane.showMessageDialog(this, "Vivienda registrada e integrada a la copropiedad con éxito.", "Registro Exitoso", JOptionPane.INFORMATION_MESSAGE);

            cargarViviendasEnTabla();

            txtIdVivienda.setText("");
            txtArea.setText("");
            txtPropietario.setText("");
            txtCedula.setText("");
            txtDireccion.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El campo 'Área' debe ser un valor numérico válido (use el punto para decimales).", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarViviendaActionPerformed

    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        // 1. COMPROBAR SELECCIÓN DE LA TABLA
        int filaSeleccionada = tblViviendas.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione de la tabla la vivienda que desea eliminar.",
                    "Selección Requerida", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. CONFIRMACIÓN DE SEGURIDAD PARA EL USUARIO
        int respuesta = JOptionPane.showConfirmDialog(this,
                "¿Está completamente seguro de eliminar esta vivienda?\nEsta acción no se puede deshacer.",
                "Confirmar Eliminación", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);

        if (respuesta != JOptionPane.YES_OPTION) {
            return; // Operación cancelada por el usuario
        }

        try {
            // 3. CARGAR ESTRUCTURAS ACTUALES EN MEMORIA
            ControladorPersistencia persistencia = new ControladorPersistencia();
            List<Comunidad> comunidades = persistencia.cargarComunidades();
            List<Vivienda> viviendasTotales = persistencia.cargarViviendas(comunidades);

            if (filaSeleccionada < viviendasTotales.size()) {
                // 4. LOCALIZAR OBJETO MEDIANTE ÍNDICE
                Vivienda viviendaAEliminar = viviendasTotales.get(filaSeleccionada);

                // 5. REMOCIÓN SÍNCRONA EN MEMORIA RAM
                // La removemos de la comunidad a la que pertenecía internamente
                if (viviendaAEliminar.getComunidad() != null) {
                    viviendaAEliminar.getComunidad().getListaViviendas().remove(viviendaAEliminar);
                }
                // La removemos de la lista global que se mandará a escribir
                viviendasTotales.remove(filaSeleccionada);

                // 6. SOBREESCRIBIR ARCHIVO PLANO Y ACTUALIZAR UI
                persistencia.guardarViviendas(viviendasTotales);

                JOptionPane.showMessageDialog(this, "La vivienda ha sido eliminada del sistema con éxito.",
                        "Eliminación Exitosa", JOptionPane.INFORMATION_MESSAGE);

                // Refrescar tabla visual de inmediato
                cargarViviendasEnTabla();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo sincronizar la fila seleccionada con los registros.",
                        "Error de Sincronización", JOptionPane.ERROR_MESSAGE);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocurrió un error inesperado al procesar la eliminación: " + e.getMessage(),
                    "Error Crítico", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBorrarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // 1. COMPROBAR SELECCIÓN DE LA TABLA
        int filaSeleccionada = tblViviendas.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione de la tabla la vivienda que desea editar.",
                    "Selección Requerida", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. CAPTURA Y VALIDACIÓN DE DATOS DEL FORMULARIO
        String idNueva = txtIdVivienda.getText().trim();
        String areaTexto = txtArea.getText().trim();
        String propietario = txtPropietario.getText().trim();
        String cedula = txtCedula.getText().trim();
        String direccion = txtDireccion.getText().trim();

        if (idNueva.isEmpty() || areaTexto.isEmpty() || propietario.isEmpty() || cedula.isEmpty() || direccion.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos con los nuevos datos.",
                    "Campos Incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double nuevaArea = Double.parseDouble(areaTexto);
            if (nuevaArea <= 0) {
                JOptionPane.showMessageDialog(this, "El área debe ser un valor numérico mayor a cero.", "Datos Inválidos", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 3. CARGAR LA PERSISTENCIA EN MEMORIA RAM
            ControladorPersistencia persistencia = new ControladorPersistencia();
            List<Comunidad> comunidades = persistencia.cargarComunidades();
            List<Vivienda> viviendasTotales = persistencia.cargarViviendas(comunidades);

            // 4. ALGORITMO DE LOCALIZACIÓN INDEXADA
            // Buscamos el objeto original en base a la posición idéntica de la JTable
            if (filaSeleccionada >= viviendasTotales.size()) {
                JOptionPane.showMessageDialog(this, "Error de desincronización de datos.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            Vivienda viviendaAEditar = viviendasTotales.get(filaSeleccionada);

            // 5. APLICAR MUTACIÓN EN CALIENTE Y MANTENER INTEGRIDAD
            // Modificamos sus atributos simples mediante setters
            viviendaAEditar.setAreaVivienda(nuevaArea);
            viviendaAEditar.setNombrePropietario(propietario);
            viviendaAEditar.setCedulaPropietario(cedula);
            viviendaAEditar.setDireccion(direccion);

            // Si el usuario decidió cambiar el ID identificador de la vivienda
            if (!viviendaAEditar.getIdVivienda().equals(idNueva)) {
                // Validamos que el nuevo ID no esté duplicado en el sistema
                for (Vivienda v : viviendasTotales) {
                    if (v.getIdVivienda().equalsIgnoreCase(idNueva) && v != viviendaAEditar) {
                        JOptionPane.showMessageDialog(this, "El ID '" + idNueva + "' ya está asignado a otra vivienda.",
                                "ID Duplicado", JOptionPane.ERROR_MESSAGE);
                        return;
                    }
                }
                viviendaAEditar.setIdVivienda(idNueva);
            }

            // 6. PERSISTIR CAMBIOS EN DISCO Y REFRESCAR ELEMENTOS VISUALES
            persistencia.guardarViviendas(viviendasTotales);

            JOptionPane.showMessageDialog(this, "¡La vivienda se ha modificado correctamente!",
                    "Edición Exitosa", JOptionPane.INFORMATION_MESSAGE);

            // Limpieza de interfaz
            txtIdVivienda.setText("");
            txtArea.setText("");
            txtPropietario.setText("");
            txtCedula.setText("");
            txtDireccion.setText("");

            cargarViviendasEnTabla();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El campo 'Área' debe ser un valor numérico válido (use el punto para decimales).",
                    "Error de Formato", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void tblViviendasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblViviendasMouseClicked
        // 1. OBTENER LA FILA SELECCIONADA POR EL USUARIO
        int filaSeleccionada = tblViviendas.getSelectedRow();

        // Si por algún motivo se hace clic fuera de una fila válida, detenemos el método
        if (filaSeleccionada == -1) {
            return;
        }

        // 2. EXTRAER LOS DATOS DE LAS CELDAS Y PASARLOS AL FORMULARIO
        // Columna 0: ID Vivienda
        txtIdVivienda.setText(modeloTabla.getValueAt(filaSeleccionada, 0).toString());

        // Columna 1: Área de la Vivienda (Se convierte de double a String automáticamente)
        txtArea.setText(modeloTabla.getValueAt(filaSeleccionada, 1).toString());

        // Columna 2: Nombre del Propietario
        txtPropietario.setText(modeloTabla.getValueAt(filaSeleccionada, 2).toString());

        // Columna 3: Cédula del Propietario
        txtCedula.setText(modeloTabla.getValueAt(filaSeleccionada, 3).toString());

        // Columna 4: Dirección Física
        txtDireccion.setText(modeloTabla.getValueAt(filaSeleccionada, 4).toString());
    }//GEN-LAST:event_tblViviendasMouseClicked

