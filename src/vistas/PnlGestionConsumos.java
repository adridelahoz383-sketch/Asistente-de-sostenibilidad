    /**
     * Busca las viviendas registradas en el archivo txt y llena el JComboBox
     */
    private void cargarSelectorViviendas() {
        boxViviendas.removeAllItems();
        ControladorPersistencia dePersistencia = new ControladorPersistencia();
        List<Comunidad> comunidades = dePersistencia.cargarComunidades();
        boxViviendas.addItem("Seleccione...");
        if (!comunidades.isEmpty()) {
            List<Vivienda> viviendas = dePersistencia.cargarViviendas(comunidades);
            for (Vivienda viv : viviendas) {
                // Añadimos cada ID de vivienda como opción en el desplegable
                boxViviendas.addItem(viv.getIdVivienda());
            }
        }
    }

    private void cargarConsumosEnTabla() {
        modeloTabla.setRowCount(0); // Limpiamos filas viejas
        ControladorPersistencia dePersistencia = new ControladorPersistencia();
        List<Comunidad> comunidades = dePersistencia.cargarComunidades();

        if (!comunidades.isEmpty()) {
            List<Vivienda> viviendas = dePersistencia.cargarViviendas(comunidades);
            List<Consumo> consumos = dePersistencia.cargarConsumos(viviendas);

            for (Consumo con : consumos) {
                // Buscamos el dueño de este consumo para mostrarlo en la primera celda
                String idViv = "Desconocido";
                for (Vivienda v : viviendas) {
                    if (v.getListaConsumos().contains(con)) {
                        idViv = v.getIdVivienda();
                        break;
                    }
                }

                // AGREGAMOS LA FILA A LA TABLA
                modeloTabla.addRow(new Object[]{
                    idViv,
                    con.getTipoServicio(),
                    con.getValorConsumido(),
                    con.getFechaFormateada(), // <--- ¡AQUÍ SE CARGA COMO "Enero/2026"!
                    con.getEstadoSostenibilidad()
                });
            }
        }
    }

