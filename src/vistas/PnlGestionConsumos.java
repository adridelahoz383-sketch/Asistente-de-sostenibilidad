    private void btnGuardarConsumoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarConsumoActionPerformed
        // 1. CAPTURA DE DATOS DESDE LOS COMPONENTES REALES DE TU PANEL
        String idViviendaSeleccionada = (boxViviendas.getSelectedItem() != null) ? boxViviendas.getSelectedItem().toString() : null;
        String servicioSeleccionado = (boxServicio.getSelectedItem() != null) ? boxServicio.getSelectedItem().toString() : null;
        String mesSeleccionado = (boxMes.getSelectedItem() != null) ? boxMes.getSelectedItem().toString() : null;
        String valorTexto = txtValor.getText();
        String anioTexto = txtAnio.getText();

// 2. VALIDACIÓN DE CAMPOS VACÍOS
        if (idViviendaSeleccionada == null || servicioSeleccionado == null || mesSeleccionado == null
                || valorTexto.trim().isEmpty() || anioTexto.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos antes de guardar.",
                    "Campos Incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // 3. CONVERSIÓN DE TIPOS Y VALIDACIONES NUMÉRICAS
            double valorConsumido = Double.parseDouble(valorTexto.trim());
            int anioDigitado = Integer.parseInt(anioTexto.trim());
            int mesNumero = boxMes.getSelectedIndex(); // Enero es Index 0 -> Mes 1

            if (valorConsumido < 0) {
                JOptionPane.showMessageDialog(this, "El valor consumido no puede ser un número negativo.", "Error de Datos", JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (anioDigitado < 2000 || anioDigitado > 2100) {
                JOptionPane.showMessageDialog(this, "Por favor, ingrese un año válido.", "Error de Rango", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 4. EL PASO CLAVE DE COMPOSICIÓN: INSTANCIAR EL OBJETO PERIODO
            Periodo periodoNuevo = new Periodo(mesNumero, anioDigitado);

            // 5. INSTANCIACIÓN POLIMÓRFICA SELECCIONANDO LA SUBCLASE CORRECTA
            Consumo nuevoConsumo;
            switch (servicioSeleccionado.toUpperCase()) {
                case "AGUA":
                    nuevoConsumo = new ConsumoAgua(valorConsumido, periodoNuevo);
                    break;
                case "GAS":
                    nuevoConsumo = new ConsumoGas(valorConsumido, periodoNuevo);
                    break;
                case "ENERGIA":
                case "ENERGÍA":
                    nuevoConsumo = new ConsumoLuz(valorConsumido, periodoNuevo);
                    break;
                default:
                    JOptionPane.showMessageDialog(this, "El tipo de servicio seleccionado no es válido.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
            }

            // Ejecutamos de forma automática el cálculo de sostenibilidad
            nuevoConsumo.calcularEstadoSostenibilidad();

            // 6. ENLAZAR CON EL CONTROLADOR DE PERSISTENCIA Y ACTUALIZAR MEMORIA
            ControladorPersistencia persistencia = new ControladorPersistencia();

            List<Comunidad> comunidades = persistencia.cargarComunidades();
            List<Vivienda> viviendas = persistencia.cargarViviendas(comunidades);

            // Forzamos la carga de consumos desde el archivo plano (.txt) para asegurar consistencia
            persistencia.cargarConsumos(viviendas);

            // Buscamos la vivienda seleccionada en la memoria RAM
            Vivienda viviendaDestino = null;
            for (Vivienda viv : viviendas) {
                if (viv.getIdVivienda().equals(idViviendaSeleccionada)) {
                    viviendaDestino = viv;
                    break;
                }
            }

            if (viviendaDestino == null) {
                JOptionPane.showMessageDialog(this, "La vivienda seleccionada no se encuentra registrada.", "Error de Integridad", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // ==========================================
            // NUEVA VALIDACIÓN DE CONTROL DE DUPLICADOS
            // ==========================================
            if (viviendaDestino.existeConsumo(nuevoConsumo.getTipoServicio(), periodoNuevo)) {
                JOptionPane.showMessageDialog(this,
                        "Ya existe un registro de " + nuevoConsumo.getTipoServicio() + " "
                        + "para el periodo seleccionado (" + nuevoConsumo.getFechaFormateada() + ").\n"
                        + "No se permiten consumos duplicados para el mismo mes.",
                        "Registro Duplicado",
                        JOptionPane.ERROR_MESSAGE);
                return; // Rompemos la ejecución para impedir la sobreescritura o duplicidad
            }
            // ==========================================

            // Agregamos el consumo recién creado si pasó la validación de arriba
            viviendaDestino.agregarConsumo(nuevoConsumo);

            // Guardamos físicamente en el archivo de texto plano
            persistencia.guardarConsumos(viviendas);

            // 7. MUESTRA DE RESULTADOS Y LIMPIEZA VISUAL
            JOptionPane.showMessageDialog(this, "¡Consumo registrado exitosamente!\n"
                    + "Servicio: " + nuevoConsumo.getTipoServicio() + "\n"
                    + "Estado Sostenible: " + nuevoConsumo.getEstadoSostenibilidad(),
                    "Operación Exitosa", JOptionPane.INFORMATION_MESSAGE);

            // Limpiamos los campos de texto editables
            limpiarCampos();

            // Refrescamos nuestra tabla visual de inmediato
            cargarConsumosEnTabla();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Asegúrese de ingresar números válidos en los campos de Año y Valor.",
                    "Error de Formato", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarConsumoActionPerformed

    private void tblConsumosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblConsumosMouseClicked
        int filaSeleccionada = tblConsumos.getSelectedRow();
        if (filaSeleccionada == -1) {
            return;
        }

        // 1. Recuperamos el ID de la vivienda, servicio y valor de forma normal
        boxViviendas.setSelectedItem(modeloTabla.getValueAt(filaSeleccionada, 0).toString());
        boxServicio.setSelectedItem(modeloTabla.getValueAt(filaSeleccionada, 1).toString());
        txtValor.setText(modeloTabla.getValueAt(filaSeleccionada, 2).toString());

        // 2. RECUPERAMOS LA FECHA COMPUESTA (Ej: "Enero/2026")
        String fechaCompuesta = modeloTabla.getValueAt(filaSeleccionada, 3).toString(); // Columna 3 (Fecha)

        // Separamos el texto usando el carácter '/' como delimitador
        String[] partes = fechaCompuesta.split("/");
        if (partes.length == 2) {
            String mesTexto = partes[0].trim(); // "Enero"
            String anioTexto = partes[1].trim(); // "2026"

            // Seteamos el año directamente en el cuadro de texto
            txtAnio.setText(anioTexto);

            // 3. MAPEO INVERSO: Traducir el nombre del mes a su formato visual en el JComboBox
            // Si en tu JComboBox los meses están como "01", "02", puedes usar este mapeo rápido:
            int indiceMes = -1;
            String[] nombres = {"Enero", "Febrero", "Marzo", "Abril", "Mayo", "Junio",
                "Julio", "Agosto", "Septiembre", "Octubre", "Noviembre", "Diciembre"};

            for (int i = 0; i < nombres.length; i++) {
                if (nombres[i].equalsIgnoreCase(mesTexto)) {
                    indiceMes = i + 1;
                    break;
                }
            }

            // Seleccionamos el índice exacto en tu boxMes (0 para "01", 1 para "02", etc.)
            if (indiceMes != -1) {
                boxMes.setSelectedIndex(indiceMes);
            }
        }

    }//GEN-LAST:event_tblConsumosMouseClicked

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed

        int filaSeleccionada = tblConsumos.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione de la tabla el consumo que desea editar.",
                    "Selección Requerida", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. CAPTURA Y VALIDACIÓN DE LOS NUEVOS DATOS DEL FORMULARIO
        String idViviendaNueva = (boxViviendas.getSelectedItem() != null) ? boxViviendas.getSelectedItem().toString() : null;
        String servicioNuevo = (boxServicio.getSelectedItem() != null) ? boxServicio.getSelectedItem().toString() : null;
        String valorTexto = txtValor.getText();
        String anioTexto = txtAnio.getText();

        if (idViviendaNueva == null || servicioNuevo == null || valorTexto.trim().isEmpty() || anioTexto.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos del formulario con los nuevos datos.",
                    "Campos Incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double nuevoValor = Double.parseDouble(valorTexto.trim());
            int nuevoAnio = Integer.parseInt(anioTexto.trim());
            int nuevoMesNum = boxMes.getSelectedIndex() + 1; // Enero es Index 0 -> Mes 1

            if (nuevoValor < 0 || nuevoAnio < 2000) {
                JOptionPane.showMessageDialog(this, "Por favor, ingrese valores numéricos coherentes.", "Datos Inválidos", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // --- CONSTRUCCIÓN DEL OBJETO COMPUESTO PERIODO ---
            Periodo nuevoPeriodo = new Periodo(nuevoMesNum, nuevoAnio);

            // 3. CARGAR LA PERSISTENCIA EN MEMORIA
            ControladorPersistencia persistencia = new ControladorPersistencia();
            List<Comunidad> comunidades = persistencia.cargarComunidades();
            List<Vivienda> viviendas = persistencia.cargarViviendas(comunidades);
            persistencia.cargarConsumos(viviendas); // Esto llena las listas internas de cada vivienda

            // 4. ALGORITMO DE LOCALIZACIÓN INDEXADA (Tu lógica intacta)
            int contadorFilaGlobal = 0;
            Consumo consumoAEditar = null;
            Vivienda viviendaOrigenDelConsumo = null;

            for (Vivienda viv : viviendas) {
                List<Consumo> listaConsumosDeEstaVivienda = viv.getListaConsumos();
                for (Consumo con : listaConsumosDeEstaVivienda) {
                    if (contadorFilaGlobal == filaSeleccionada) {
                        consumoAEditar = con;
                        viviendaOrigenDelConsumo = viv;
                        break;
                    }
                    contadorFilaGlobal++;
                }
                if (consumoAEditar != null) {
                    break;
                }
            }

            // 5. APLICAR LOS CAMBIOS Y RECALCULAR POLIMORFISMO
            if (consumoAEditar != null && viviendaOrigenDelConsumo != null) {

                // Si el usuario cambió el consumo de vivienda, lo removemos de la vieja y lo pasamos a la nueva
                if (!viviendaOrigenDelConsumo.getIdVivienda().equals(idViviendaNueva)) {
                    viviendaOrigenDelConsumo.getListaConsumos().remove(consumoAEditar);

                    // Buscamos la nueva vivienda destino
                    for (Vivienda vNueva : viviendas) {
                        if (vNueva.getIdVivienda().equals(idViviendaNueva)) {
                            vNueva.agregarConsumo(consumoAEditar);
                            break;
                        }
                    }
                }

                // Si cambió el tipo de servicio (ej: pasó de Agua a Gas), debemos instanciar el objeto correcto
                if (!consumoAEditar.getTipoServicio().equalsIgnoreCase(servicioNuevo)) {
                    // Removemos el objeto viejo de la vivienda donde quedó asignado actualmente en memoria
                    for (Vivienda v : viviendas) {
                        if (v.getIdVivienda().equals(idViviendaNueva)) {
                            v.getListaConsumos().remove(consumoAEditar);

                            // REFACTORIZACIÓN: Instanciamos la subclase correcta inyectando el objeto nuevoPeriodo
                            if (servicioNuevo.equalsIgnoreCase("AGUA")) {
                                consumoAEditar = new ConsumoAgua(nuevoValor, nuevoPeriodo);
                            } else if (servicioNuevo.equalsIgnoreCase("GAS")) {
                                consumoAEditar = new ConsumoGas(nuevoValor, nuevoPeriodo);
                            } else if (servicioNuevo.equalsIgnoreCase("ENERGIA") || servicioNuevo.equalsIgnoreCase("ENERGÍA")) {
                                consumoAEditar = new ConsumoLuz(nuevoValor, nuevoPeriodo);
                            }

                            v.agregarConsumo(consumoAEditar);
                            break;
                        }
                    }
                } else {
                    // REFACTORIZACIÓN: El servicio es el mismo, mutamos los atributos usando setters.
                    // Reemplazamos setMes y setAnio por setPeriodo pasándole el objeto completo
                    consumoAEditar.setValorConsumido(nuevoValor);
                    consumoAEditar.setPeriodo(nuevoPeriodo);
                }

                // Forzamos a recalcular las reglas de negocio de sostenibilidad del objeto actualizado
                consumoAEditar.calcularEstadoSostenibilidad();

                // 6. PERSISTIR CAMBIOS EN EL ARCHIVO PLANO Y REFRESCAR VISTA
                persistencia.guardarConsumos(viviendas);

                JOptionPane.showMessageDialog(this, "El registro de consumo se ha modificado correctamente.",
                        "Edición Exitosa", JOptionPane.INFORMATION_MESSAGE);

                // Limpieza de campos de texto
                limpiarCampos();

                // Refrescamos la tabla visual
                cargarConsumosEnTabla();
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Verifique los formatos numéricos de valor y año.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnEditarActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // 1. COMPROBAR QUE HAYA UNA FILA SELECCIONADA EN LA TABLA
        int filaSeleccionada = tblConsumos.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione de la tabla el registro de consumo que desea eliminar.",
                    "Selección Requerida", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. PEDIR CONFIRMACIÓN AL USUARIO (Principio de usabilidad para evitar pérdidas accidentales)
        int confirmar = JOptionPane.showConfirmDialog(this,
                "¿Está completamente seguro de eliminar el registro de consumo seleccionado?\nEsta acción no se puede deshacer.",
                "Confirmar Eliminación", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);

        if (confirmar != JOptionPane.YES_OPTION) {
            return; // Si el usuario presiona "No" o cierra la ventana, detenemos el proceso
        }

        try {
            // 3. CARGAR EL CONTEXTO ACTUAL DE LA PERSISTENCIA EN MEMORIA
            ControladorPersistencia persistencia = new ControladorPersistencia();
            List<Comunidad> comunidades = persistencia.cargarComunidades();
            List<Vivienda> viviendas = persistencia.cargarViviendas(comunidades);

            // Forzamos a que se pueblen las listas internas de consumos de cada vivienda
            persistencia.cargarConsumos(viviendas);

            // 4. ALGORITMO DE DETECCIÓN INDEXADA
            int contadorFilaGlobal = 0;
            boolean registroEliminado = false;

            // Recorremos las viviendas y sus consumos internos en el mismo orden que se cargan en la tabla
            for (Vivienda viv : viviendas) {
                List<Consumo> listaConsumosDeEstaVivienda = viv.getListaConsumos();

                for (int i = 0; i < listaConsumosDeEstaVivienda.size(); i++) {
                    if (contadorFilaGlobal == filaSeleccionada) {
                        // Encontramos el consumo en la vivienda correcta. Lo removemos usando su índice interno.
                        listaConsumosDeEstaVivienda.remove(i);
                        registroEliminado = true;
                        break; // Rompemos el ciclo interno de consumos
                    }
                    contadorFilaGlobal++; // Incrementamos para emparejar con el índice de las filas de la JTable
                }
                if (registroEliminado) {
                    break; // Rompemos el ciclo externo de viviendas si ya cumplimos la tarea
                }
            }

            // 5. REESCRITURA DEL ARCHIVO PLANO Y ACTUALIZACIÓN VISUAL
            if (registroEliminado) {
                // Guardamos la lista estructurada de viviendas usando tu firma de persistencia real
                persistencia.guardarConsumos(viviendas);

                JOptionPane.showMessageDialog(this, "El registro de consumo ha sido eliminado exitosamente.",
                        "Eliminación Exitosa", JOptionPane.INFORMATION_MESSAGE);

                // Limpiamos los campos del formulario por si los datos del registro eliminado estaban cargados
                limpiarCampos();

                // Refrescamos la JTable directamente desde el archivo consumos.txt recién actualizado
                cargarConsumosEnTabla();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo sincronizar la fila seleccionada con los registros en memoria.",
                        "Error de Sincronización", JOptionPane.ERROR_MESSAGE);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocurrió un error inesperado al eliminar: " + e.getMessage(),
                    "Error Crítico", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

