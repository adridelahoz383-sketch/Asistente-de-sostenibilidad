    public static String Capitalizar(String texto) {
        if (texto == null || texto.isEmpty()) {
            return texto;
        }

        texto = texto.trim();
        if (texto.isEmpty()) {
            return texto;
        }

        return texto.substring(0, 1).toUpperCase() + texto.substring(1).toLowerCase();
    }
    
    

